"""Cosmos-compatible action expert for FastWAM MoT coupling.

Mirrors the original FastWAM ActionDiT idea (a transformer over action tokens that
joint-attends with the video DiT). Two widths are supported:

* full-size: stock Cosmos ``Block``s with the same hidden size as the video DiT,
  initialised by copying the video blocks exactly;
* compact: smaller action residual/MLP width, but Q/K/V still project to the
  video attention width (same n_heads and head_dim) so MoT can concatenate K/V.

Compact blocks are interpolation-initialised from the Cosmos video DiT: shared
attention and MLP matrices are resized with the same sequential 1D linear
interpolation policy as the original Wan preprocessing script, while AdaLN
packed outputs resize each shift/scale/gate chunk separately. Action tokens are
a length-``Ta`` sequence (one token per action step). Their RoPE is generated by
reusing the video net's 3-D RoPE embedder on a ``[Ta, 1, 1]`` grid, so only the
temporal axis varies.
"""
from __future__ import annotations

import torch
import torch.nn as nn
import torch.nn.functional as F
from einops import rearrange

from fastwam.utils.logging_config import get_logger

logger = get_logger(__name__)


def _interpolate_last_dim(tensor: torch.Tensor, new_size: int) -> torch.Tensor:
    if tensor.shape[-1] == new_size:
        return tensor
    flat = tensor.reshape(-1, 1, tensor.shape[-1]).to(torch.float32)
    flat = F.interpolate(flat, size=new_size, mode="linear", align_corners=True)
    return flat.reshape(*tensor.shape[:-1], new_size)


def _resize_tensor_to_shape(src: torch.Tensor, target_shape: tuple[int, ...]) -> torch.Tensor:
    """Sequential 1D linear interpolation, matching scripts/preprocess_action_dit_backbone.py."""
    if tuple(src.shape) == tuple(target_shape):
        return src

    out = src.to(torch.float32)
    while out.ndim < len(target_shape):
        out = out.unsqueeze(0)
    while out.ndim > len(target_shape):
        if out.shape[0] != 1:
            raise ValueError(f"Cannot reduce tensor rank: src={tuple(src.shape)}, target={target_shape}")
        out = out.squeeze(0)

    for dim, new_size in enumerate(target_shape):
        if out.shape[dim] == new_size:
            continue
        perm = [i for i in range(out.ndim) if i != dim] + [dim]
        inv_perm = [0] * out.ndim
        for i, p in enumerate(perm):
            inv_perm[p] = i
        out_perm = out.permute(*perm).contiguous()
        prefix_shape = out_perm.shape[:-1]
        out_perm = _interpolate_last_dim(out_perm, int(new_size))
        out = out_perm.reshape(*prefix_shape, int(new_size)).permute(*inv_perm).contiguous()

    if tuple(out.shape) != tuple(target_shape):
        raise ValueError(f"Resize produced wrong shape: src={tuple(src.shape)}, target={target_shape}, got={tuple(out.shape)}")
    return out.to(dtype=src.dtype)


def _copy_resized_(dst: torch.Tensor, src: torch.Tensor, alpha_scale_last_dim: bool = False):
    value = _resize_tensor_to_shape(src, tuple(dst.shape))
    if alpha_scale_last_dim and src.ndim >= 2 and src.shape[-1] != dst.shape[-1]:
        alpha = (float(src.shape[-1]) / float(dst.shape[-1])) ** 0.5
        value = value.to(torch.float32) * alpha
    dst.copy_(value.to(device=dst.device, dtype=dst.dtype))


def _copy_linear_resized_(dst: nn.Linear, src: nn.Linear):
    _copy_resized_(dst.weight, src.weight, alpha_scale_last_dim=True)
    if dst.bias is not None and src.bias is not None:
        _copy_resized_(dst.bias, src.bias)


def _copy_three_way_linear_(dst: nn.Linear, src: nn.Linear):
    """Resize Linear weights whose output dim is packed as [shift, scale, gate]."""
    d_chunk = dst.weight.shape[0] // 3
    s_chunk = src.weight.shape[0] // 3
    for i in range(3):
        dst_slice = dst.weight[i * d_chunk : (i + 1) * d_chunk]
        src_slice = src.weight[i * s_chunk : (i + 1) * s_chunk]
        _copy_resized_(dst_slice, src_slice, alpha_scale_last_dim=True)
    if dst.bias is not None and src.bias is not None:
        for i in range(3):
            dst_slice = dst.bias[i * d_chunk : (i + 1) * d_chunk]
            src_slice = src.bias[i * s_chunk : (i + 1) * s_chunk]
            _copy_resized_(dst_slice, src_slice)


def _copy_adaln_resized_(dst: nn.Sequential, src: nn.Sequential):
    if len(dst) == len(src) == 3:
        _copy_linear_resized_(dst[1], src[1])
        _copy_three_way_linear_(dst[2], src[2])
    elif len(dst) == len(src) == 2:
        _copy_three_way_linear_(dst[1], src[1])


class CompactCosmosBlock(nn.Module):
    """Cosmos-compatible block with smaller token width but full MoT attention width.

    Cosmos' stock ``Block`` sets ``head_dim = x_dim // num_heads``. That makes a
    compact action hidden size incompatible with MoT K/V concatenation against the
    video DiT. This block keeps ``x_dim`` small (for residual/MLP width) while
    forcing Q/K/V to ``num_heads * attention_head_dim`` so it can joint-attend with
    the video stream.
    """

    def __init__(
        self,
        x_dim: int,
        context_dim: int,
        num_heads: int,
        attention_head_dim: int,
        ffn_dim: int,
        use_adaln_lora: bool = True,
        adaln_lora_dim: int = 256,
        backend: str = "torch",
    ):
        super().__init__()
        from cosmos_predict2._src.predict2.networks.minimal_v4_dit import (
            Attention,
            GPT2FeedForward,
        )

        self.x_dim = int(x_dim)
        self.num_heads = int(num_heads)
        self.attention_head_dim = int(attention_head_dim)
        self.layer_norm_self_attn = nn.LayerNorm(self.x_dim, elementwise_affine=False, eps=1e-6)
        self.self_attn = Attention(
            self.x_dim,
            None,
            self.num_heads,
            self.attention_head_dim,
            qkv_format="bshd",
            backend=backend,
        )
        self.layer_norm_cross_attn = nn.LayerNorm(self.x_dim, elementwise_affine=False, eps=1e-6)
        self.cross_attn = Attention(
            self.x_dim,
            context_dim,
            self.num_heads,
            self.attention_head_dim,
            qkv_format="bshd",
            backend=backend,
        )
        self.layer_norm_mlp = nn.LayerNorm(self.x_dim, elementwise_affine=False, eps=1e-6)
        self.mlp = GPT2FeedForward(self.x_dim, int(ffn_dim))

        self.use_adaln_lora = bool(use_adaln_lora)
        if self.use_adaln_lora:
            self.adaln_modulation_self_attn = nn.Sequential(
                nn.SiLU(),
                nn.Linear(self.x_dim, adaln_lora_dim, bias=False),
                nn.Linear(adaln_lora_dim, 3 * self.x_dim, bias=False),
            )
            self.adaln_modulation_cross_attn = nn.Sequential(
                nn.SiLU(),
                nn.Linear(self.x_dim, adaln_lora_dim, bias=False),
                nn.Linear(adaln_lora_dim, 3 * self.x_dim, bias=False),
            )
            self.adaln_modulation_mlp = nn.Sequential(
                nn.SiLU(),
                nn.Linear(self.x_dim, adaln_lora_dim, bias=False),
                nn.Linear(adaln_lora_dim, 3 * self.x_dim, bias=False),
            )
        else:
            self.adaln_modulation_self_attn = nn.Sequential(
                nn.SiLU(), nn.Linear(self.x_dim, 3 * self.x_dim, bias=False)
            )
            self.adaln_modulation_cross_attn = nn.Sequential(
                nn.SiLU(), nn.Linear(self.x_dim, 3 * self.x_dim, bias=False)
            )
            self.adaln_modulation_mlp = nn.Sequential(
                nn.SiLU(), nn.Linear(self.x_dim, 3 * self.x_dim, bias=False)
            )
        self.init_weights()

    def init_weights(self):
        if hasattr(self.self_attn, "init_weights"):
            self.self_attn.init_weights()
        if hasattr(self.cross_attn, "init_weights"):
            self.cross_attn.init_weights()
        if hasattr(self.mlp, "init_weights"):
            self.mlp.init_weights()
        for mod in (
            self.adaln_modulation_self_attn,
            self.adaln_modulation_cross_attn,
            self.adaln_modulation_mlp,
        ):
            if len(mod) == 3:
                nn.init.normal_(mod[1].weight, std=self.x_dim**-0.5)
                nn.init.zeros_(mod[2].weight)
            else:
                nn.init.zeros_(mod[1].weight)

    @staticmethod
    def _mod_grid(norm_layer, x, scale, shift):
        scale = rearrange(scale, "b t d -> b t 1 1 d").type_as(x)
        shift = rearrange(shift, "b t d -> b t 1 1 d").type_as(x)
        return norm_layer(x) * (1 + scale) + shift

    @staticmethod
    def _gate_grid(gate, out):
        return out * rearrange(gate, "b t d -> b t 1 1 d").type_as(out)

    @staticmethod
    def _mods(mod, emb, adaln_lora):
        out = mod(emb)
        if adaln_lora is not None:
            out = out + adaln_lora
        return out.chunk(3, dim=-1)

    def forward(
        self,
        x_B_T_H_W_D: torch.Tensor,
        emb_B_T_D: torch.Tensor,
        crossattn_emb: torch.Tensor,
        rope_emb_L_1_1_D: torch.Tensor | None = None,
        adaln_lora_B_T_3D: torch.Tensor | None = None,
        **_,
    ) -> torch.Tensor:
        shift_sa, scale_sa, gate_sa = self._mods(
            self.adaln_modulation_self_attn, emb_B_T_D, adaln_lora_B_T_3D
        )
        shift_ca, scale_ca, gate_ca = self._mods(
            self.adaln_modulation_cross_attn, emb_B_T_D, adaln_lora_B_T_3D
        )
        shift_mlp, scale_mlp, gate_mlp = self._mods(
            self.adaln_modulation_mlp, emb_B_T_D, adaln_lora_B_T_3D
        )

        B, T, H, W, D = x_B_T_H_W_D.shape
        n = self._mod_grid(self.layer_norm_self_attn, x_B_T_H_W_D, scale_sa, shift_sa)
        out = self.self_attn(
            n.reshape(B, T * H * W, D),
            rope_emb=rope_emb_L_1_1_D,
        ).view(B, T, H, W, D)
        x_B_T_H_W_D = x_B_T_H_W_D + self._gate_grid(gate_sa, out)

        n = self._mod_grid(self.layer_norm_cross_attn, x_B_T_H_W_D, scale_ca, shift_ca)
        out = self.cross_attn(n.reshape(B, T * H * W, D), crossattn_emb).view(B, T, H, W, D)
        x_B_T_H_W_D = x_B_T_H_W_D + self._gate_grid(gate_ca, out)

        n = self._mod_grid(self.layer_norm_mlp, x_B_T_H_W_D, scale_mlp, shift_mlp)
        out = self.mlp(n)
        return x_B_T_H_W_D + self._gate_grid(gate_mlp, out)


class CosmosActionExpert(nn.Module):
    def __init__(
        self,
        action_dim: int,
        model_channels: int,
        num_blocks: int,
        num_heads: int,
        crossattn_emb_channels: int = 1024,
        action_hidden_dim: int | None = None,
        action_ffn_dim: int | None = None,
        attention_head_dim: int | None = None,
        use_adaln_lora: bool = True,
        adaln_lora_dim: int = 256,
    ):
        super().__init__()
        from cosmos_predict2._src.predict2.networks.minimal_v4_dit import (
            Block,
            TimestepEmbedding,
            Timesteps,
        )

        self.action_dim = int(action_dim)
        self.model_channels = int(model_channels)
        self.hidden_dim = int(action_hidden_dim or model_channels)
        self.num_heads = int(num_heads)
        self.attention_head_dim = int(attention_head_dim or (model_channels // num_heads))
        self.ffn_dim = int(action_ffn_dim or (4 * self.hidden_dim))
        self.is_compact = (
            self.hidden_dim != self.model_channels
            or self.attention_head_dim != self.hidden_dim // self.num_heads
        )

        # action-step token embed / un-embed (the only "new" weights besides AdaLN heads)
        self.action_encoder = nn.Linear(action_dim, self.hidden_dim)
        # LayerNorm before the head: action tokens carry large-magnitude features
        # from the joint attention with the Cosmos video DiT; without normalising
        # them the action loss explodes after the first step (same failure mode the
        # SANA variant hit). Mirrors the Cosmos final_layer's pre-projection norm.
        self.head_norm = nn.LayerNorm(self.hidden_dim)
        self.head = nn.Linear(self.hidden_dim, action_dim)
        # zero-init the output head (diffusion convention): start by predicting zero
        # velocity so the action loss begins at ~||target||^2 instead of exploding
        # (the action tokens carry large-magnitude features from the Cosmos blocks).
        nn.init.zeros_(self.head.weight)
        nn.init.zeros_(self.head.bias)

        # timestep embedding for the action diffusion (own copy; same shape as video)
        self.t_embedder = nn.Sequential(
            Timesteps(self.hidden_dim),
            TimestepEmbedding(self.hidden_dim, self.hidden_dim, use_adaln_lora=use_adaln_lora),
        )
        self.t_embedding_norm = (
            nn.RMSNorm(self.hidden_dim, eps=1e-6)
            if hasattr(nn, "RMSNorm")
            else nn.LayerNorm(self.hidden_dim)
        )

        if self.is_compact:
            self.blocks = nn.ModuleList(
                CompactCosmosBlock(
                    x_dim=self.hidden_dim,
                    context_dim=crossattn_emb_channels,
                    num_heads=num_heads,
                    attention_head_dim=self.attention_head_dim,
                    ffn_dim=self.ffn_dim,
                    use_adaln_lora=use_adaln_lora,
                    adaln_lora_dim=adaln_lora_dim,
                    backend="torch",
                )
                for _ in range(num_blocks)
            )
        else:
            self.blocks = nn.ModuleList(
                Block(
                    x_dim=self.hidden_dim,
                    context_dim=crossattn_emb_channels,
                    num_heads=num_heads,
                    mlp_ratio=self.ffn_dim / float(self.hidden_dim),
                    use_adaln_lora=use_adaln_lora,
                    adaln_lora_dim=adaln_lora_dim,
                    backend="torch",
                )
                for _ in range(num_blocks)
            )

    @torch.no_grad()
    def copy_init_from_video(self, video_net):
        """Warm-start action DiT from video DiT.

        Full-size action blocks can load the video state dict directly. Compact
        blocks use linear interpolation initialisation so the action branch keeps a
        pretrained prior while reducing residual/MLP width.
        """
        if not self.is_compact:
            for ab, vb in zip(self.blocks, video_net.blocks):
                ab.load_state_dict(vb.state_dict(), strict=False)
            try:
                self.t_embedder.load_state_dict(video_net.t_embedder.state_dict(), strict=False)
                self.t_embedding_norm.load_state_dict(video_net.t_embedding_norm.state_dict(), strict=False)
            except Exception as e:  # shapes should match, but don't hard-fail the warm start
                logger.warning("action t_embedder warm-start skipped: %s", e)
            logger.info("CosmosActionExpert: copy-initialised %d blocks from video DiT.", len(self.blocks))
            return

        self._interp_init_from_video(video_net)
        logger.info(
            "CosmosActionExpert: interpolation-initialised compact action DiT from video DiT "
            "(hidden=%d, ffn=%d, attn=%dx%d, blocks=%d).",
            self.hidden_dim,
            self.ffn_dim,
            self.num_heads,
            self.attention_head_dim,
            len(self.blocks),
        )

    @torch.no_grad()
    def _interp_init_from_video(self, video_net):
        try:
            _copy_linear_resized_(self.t_embedder[1].linear_1, video_net.t_embedder[1].linear_1)
            _copy_three_way_linear_(self.t_embedder[1].linear_2, video_net.t_embedder[1].linear_2)
            _copy_resized_(self.t_embedding_norm.weight, video_net.t_embedding_norm.weight)
        except Exception as e:
            logger.warning("compact action t_embedder interp-init skipped: %s", e)

        for ab, vb in zip(self.blocks, video_net.blocks):
            for name in ("self_attn", "cross_attn"):
                aa = getattr(ab, name)
                va = getattr(vb, name)
                for proj in ("q_proj", "k_proj", "v_proj", "output_proj"):
                    _copy_linear_resized_(getattr(aa, proj), getattr(va, proj))
                for norm in ("q_norm", "k_norm"):
                    aw = getattr(getattr(aa, norm), "weight", None)
                    vw = getattr(getattr(va, norm), "weight", None)
                    if aw is not None and vw is not None:
                        _copy_resized_(aw, vw)
            if hasattr(ab.mlp, "layer1") and hasattr(vb.mlp, "layer1"):
                _copy_linear_resized_(ab.mlp.layer1, vb.mlp.layer1)
                _copy_linear_resized_(ab.mlp.layer2, vb.mlp.layer2)
            _copy_adaln_resized_(ab.adaln_modulation_self_attn, vb.adaln_modulation_self_attn)
            _copy_adaln_resized_(ab.adaln_modulation_cross_attn, vb.adaln_modulation_cross_attn)
            _copy_adaln_resized_(ab.adaln_modulation_mlp, vb.adaln_modulation_mlp)

    def action_rope(self, video_net, Ta: int, device, dtype):
        """Reuse the video net's 3-D RoPE on a [Ta,1,1] grid -> action-step RoPE.
        fps (base_fps) is required when rope_enable_fps_modulation, else the rope
        takes the image path which asserts T==1."""
        probe = torch.zeros(1, Ta, 1, 1, self.model_channels, device=device, dtype=dtype)
        base_fps = float(getattr(video_net.pos_embedder, "base_fps", 16))
        fps = torch.full((1,), base_fps, device=device)
        return video_net.pos_embedder.generate_embeddings(probe.shape, fps=fps)

    def prepare(self, noisy_action_B_Ta_a, timesteps_B, crossattn_emb, video_net):
        """Embed action tokens + timestep emb + RoPE; return MoT stream state.

        noisy_action: [B, Ta, action_dim]; timesteps: [B] or [B,Ta]; crossattn: text.
        """
        B, Ta, _ = noisy_action_B_Ta_a.shape
        tokens = self.action_encoder(noisy_action_B_Ta_a)  # [B, Ta, D]
        ts = timesteps_B
        if ts.ndim == 1:
            ts = ts.unsqueeze(1).expand(B, Ta)  # per-token time (same value)
        t_emb, adaln_lora = self.t_embedder(ts)
        t_emb = self.t_embedding_norm(t_emb)
        rope = self.action_rope(video_net, Ta, tokens.device, tokens.dtype)
        return {
            "tokens": tokens,
            "rope": rope,
            "t_emb": t_emb,
            "adaln_lora": adaln_lora,
            "crossattn": crossattn_emb,
            "THW": (Ta, 1, 1),
        }

    def finalize(self, tokens_B_Ta_D):
        """Action tokens -> predicted velocity [B, Ta, action_dim]."""
        return self.head(self.head_norm(tokens_B_Ta_D))

    def forward_cross_attn(self, noisy_action_B_Ta_a, timesteps_B, context, video_net):
        """Cross-attention coupling: action-only self-attention + cross-attention to
        ``context`` (text + proprio + video features). The Cosmos Block.forward is
        exactly self-attn -> cross-attn(context) -> MLP, so we run the action blocks
        directly (no joint attention with the video stream). -> velocity [B,Ta,a]."""
        a = self.prepare(noisy_action_B_Ta_a, timesteps_B, context, video_net)
        B, Ta, D = a["tokens"].shape
        x = a["tokens"].view(B, Ta, 1, 1, D)  # Cosmos Block expects [B,T,H,W,D]
        for blk in self.blocks:
            x = blk(x, a["t_emb"], context, rope_emb_L_1_1_D=a["rope"],
                    adaln_lora_B_T_3D=a["adaln_lora"])
        return self.finalize(x.view(B, Ta, D))
